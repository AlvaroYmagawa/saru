// Bundles the app (main, preload, renderer), the CLI and the plugin's context script.
import { build } from "esbuild";
import { cpSync, mkdirSync } from "node:fs";

const common = { bundle: true, sourcemap: "linked", logLevel: "warning", target: "node22" };

mkdirSync("dist", { recursive: true });
await Promise.all([
  build({ ...common, entryPoints: ["src/main/index.ts"], outfile: "dist/main.cjs", platform: "node", format: "cjs", external: ["electron"] }),
  build({ ...common, entryPoints: ["src/preload/index.ts"], outfile: "dist/preload.cjs", platform: "node", format: "cjs", external: ["electron"] }),
  build({ ...common, entryPoints: ["src/renderer/app.tsx"], outfile: "dist/renderer/app.js", platform: "browser", format: "iife", target: "chrome140", jsx: "automatic", loader: { ".woff2": "file", ".ttf": "file", ".svg": "text" } }),
  build({ ...common, entryPoints: ["src/cli/saru.ts"], outfile: "dist/cli.cjs", platform: "node", format: "cjs", banner: { js: "#!/usr/bin/env node" } }),
  // Committed, so the plugin works straight from a clone; `npm run check` fails when it's stale.
  build({ ...common, sourcemap: false, entryPoints: ["src/cli/guard.ts"], outfile: "plugin/scripts/guard.cjs", platform: "node", format: "cjs", banner: { js: "#!/usr/bin/env node\n// Generated by scripts/build.mjs from src/cli/guard.ts — don't edit." } }),
  build({ ...common, sourcemap: false, entryPoints: ["src/cli/saru.ts"], outfile: "plugin/scripts/saru.cjs", platform: "node", format: "cjs", banner: { js: "#!/usr/bin/env node\n// Generated by scripts/build.mjs from src/cli — don't edit." } }),
]);
cpSync("src/renderer/index.html", "dist/renderer/index.html");
cpSync("src/renderer/styles.css", "dist/renderer/styles.css");
cpSync("resources/fonts", "dist/renderer/fonts", { recursive: true });
